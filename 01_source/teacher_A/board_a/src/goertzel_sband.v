`timescale 1ns/1ps
// 32-band Goertzel spectral energy extractor (docs/10 §4, R81 A-board
// fill). Log-spaced grid 180..5409 Hz on the N=260 frame-aligned window;
// one shared datapath time-multiplexed across 32 accumulators (32 steps
// per 15.625 kHz sample, 1600 clocks available).
//
// One shared datapath is time-multiplexed across 8 band accumulators; at
// 15.625 kS/s there are ~1600 clocks per sample and a windowed sample
// costs 9 of them (1 window latch + 8 band steps), so the mux is nowhere
// near timing-critical. Samples are Hann-windowed ONCE on arrival (a
// rectangular window's -13 dB skirt two bins away would make the spectral
// shape useless; Hann gives -31 dB). The window table is generated by
// tools/gen_hann_window.py -> hann_w260.hex (Q0.14; $readmemh like the
// classifier LUT -- keep the hex next to this file for TD).
//
// Band centres: log grid k = [3..20 step1, 22, 24, 27, 30, 33, 37, 42,
// 47, 52, 58, 65, 72, 81, 90] over N=260 (60.1 Hz bins), coefficients
// GENERATED into band36_case.vh by tools/gen_band32.py -- do not hand-edit.
//
// At frame_tick each band finalises E = s1^2 + s2^2 - c*(s1*s2) and
// quantises e_q = clamp(6*msb_p(E) + 24, 0, 255): one e_q step ~ 1 dB,
// MSB-based so no divider. Finalize pauses the sample drain for ~48 clocks
// (~3% of windows); a sample arriving then advances win_idx but skips one
// accumulation -- at most 1 of 384 samples, a <=0.3% energy skew.
module goertzel_sband #(
    parameter integer N = 260
) (
    input  wire               clk,          // 25 MHz video clock
    input  wire               rst_n,
    input  wire               sample_valid, // 15.625 kHz sample strobe
    input  wire signed [15:0] sample,       // front-end sample (pre-window)
    input  wire               frame_tick,   // 60 Hz: close window, emit bands
    input  wire               acc_freeze,   // R83: freeze accumulators on unvoiced
    output reg [287:0]       bands,   // 36 x e_q; [23:0] = old NB 8 (k=4,7,11,17,26,39,59,89)        // 8 x 8-bit e_q, band 0 in [7:0]
    output reg                bands_valid   // 1-clk pulse, window closed
);
    // 2*cos(2*pi*k/N) in Q1.14 (computed values, not hand-rounded)
    function signed [15:0] band_c;
        input [5:0] i;
        begin
            case (i)
                `include "band36_case.vh"
                default: band_c = 16'sd0;
            endcase
        end
    endfunction

    // Hann window, Q0.14, generated table
    reg [15:0] w_lut [0:N-1];
    initial begin
        $readmemh("hann_w260.hex", w_lut);
    end

    // msb index of a 50-bit non-negative vector (highest set bit; 0 for 0)
    function [5:0] msb_of;
        input [49:0] v;
        integer i;
        begin
            msb_of = 6'd0;
            for (i = 0; i < 50; i = i + 1)
                if (v[i]) msb_of = i[5:0];
        end
    endfunction

    // ------------------------------------------------------ state
    reg [8:0]  win_idx;                     // 0..383, position in window
    reg signed [15:0] wx;                   // windowed sample in flight
    reg        wx_load;                     // wprod ready -> wx
    reg signed [31:0] wprod;                // sample * window product
    reg [5:0]  step_idx;                    // band step 0..7
    reg        stepping;                    // draining 8 band steps

    reg signed [23:0] s1 [0:35];             // Goertzel states (24b: the k=4
    reg signed [23:0] s2 [0:35];             // resonator gain ~10.35x on a
                                            // full-scale sample reaches 340k;
                                            // 20 bits wrapped it and silently
                                            // destroyed the bin-0 energy)

    reg        fin_busy;
    reg [5:0]  fin_idx;
    reg [2:0]  fin_step;                    // 6 cycles per band
    reg        fin_pend;                    // frame_tick arrived during finalize
    reg signed [23:0] f1, f2;
    reg signed [15:0] c_fin;
    reg signed [47:0] p_sq1, p_pr, p_sq2;
    reg signed [63:0] p_cpr;                // c(16) * (s1*s2)(48), |c|<=2
    reg signed [49:0] e_val;                // final energy (>= 0 physically)
    reg [49:0] mag;
    reg [5:0]  msb_q;

    // The resonator product c*s1 reaches ~5.4e9 (s1 ~ 10x the windowed
    // sample at the k=4 resonance) -- it MUST be computed in 36 bits. A
    // 32-bit context silently wraps it and high-energy bands read as
    // garbage (first bring-up bug: tones landed in the wrong bands).
    wire signed [39:0] cprod  = band_c(step_idx) * s1[step_idx];
    wire signed [39:0] cshift = cprod >>> 14;
    wire signed [39:0] g_step = $signed(wx) + cshift - $signed(s2[step_idx]);

    // Offset -24 (v1.3): with the canonical peak_codes=1100 mapping the
    // front end emits +-15k samples, so a band-centre tone lands at
    // msb ~40 and the old +24 bias saturated EVERY band of loud speech at
    // 255 (all shape information lost). -24 puts typical speech shape in
    // e_q ~ 130..215 with ~100 units of usable span.
    wire signed [15:0] e_q_full = msb_q * 16'sd6 - 16'sd24;
    wire [7:0] e_q_comb = (e_q_full < 0) ? 8'd0
                        : (e_q_full > 255) ? 8'd255 : e_q_full[7:0];

    integer gi;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            win_idx <= 9'd0; wx <= 16'sd0; wx_load <= 1'b0;
            wprod <= 32'sd0; step_idx <= 3'd0; stepping <= 1'b0;
            bands <= 288'd0;   // audit P2: full width (was 64'd0)
            bands_valid <= 1'b0;
            fin_busy <= 1'b0; fin_idx <= 3'd0; fin_step <= 3'd0;
            fin_pend <= 1'b0;
            f1 <= 24'sd0; f2 <= 24'sd0; c_fin <= 16'sd0;
            p_sq1 <= 48'sd0; p_pr <= 48'sd0; p_sq2 <= 48'sd0;
            p_cpr <= 64'sd0; e_val <= 50'sd0; mag <= 50'd0; msb_q <= 6'd0;
            for (gi = 0; gi < 36; gi = gi + 1) begin
                s1[gi] <= 20'sd0; s2[gi] <= 20'sd0;
            end
        end else begin
            bands_valid <= 1'b0;

            // ---------- sample drain (paused while finalize runs) ----------
            if (sample_valid)
                win_idx <= (win_idx == N - 1) ? 9'd0 : win_idx + 1'b1;

            if (!fin_busy && !acc_freeze) begin
                if (sample_valid && !stepping && !wx_load) begin
                    wprod    <= $signed(sample)
                                * $signed({2'b00, w_lut[win_idx]});
                    wx_load  <= 1'b1;
                    step_idx <= 3'd0;
                    stepping <= 1'b1;
                end else if (stepping) begin
                    if (wx_load) begin
                        wx      <= wprod >>> 14;
                        wx_load <= 1'b0;
                    end else begin
                        s1[step_idx] <= g_step[23:0];
                        s2[step_idx] <= s1[step_idx];
                        if (step_idx == 6'd35)
                            stepping <= 1'b0;
                        else
                            step_idx <= step_idx + 1'b1;
                    end
                end
            end

            // ---------- frame finalize (8 bands x 6 cycles) ----------
            if (frame_tick && !fin_busy)
                fin_pend <= 1'b1;
            if (fin_pend && !fin_busy && !stepping) begin
                fin_pend <= 1'b0;
                fin_busy <= 1'b1;
                fin_idx  <= 6'd0;
                fin_step <= 3'd0;
                f1       <= s1[0];
                f2       <= s2[0];
                c_fin    <= band_c(3'd0);
            end else if (fin_busy) begin
                case (fin_step)
                3'd0: begin
                    p_sq1    <= f1 * f1;      // s1^2
                    p_pr     <= f1 * f2;      // s1*s2
                    fin_step <= 3'd1;
                end
                3'd1: begin
                    p_sq2    <= f2 * f2;      // s2^2
                    p_cpr    <= c_fin * p_pr; // c*(s1*s2)
                    fin_step <= 3'd2;
                end
                3'd2: begin
                    e_val    <= p_sq1 + p_sq2 - (p_cpr >>> 14);
                    fin_step <= 3'd3;
                end
                3'd3: begin
                    mag      <= (e_val < 0) ? 44'd0 : e_val;
                    fin_step <= 3'd4;
                end
                3'd4: begin
                    msb_q    <= msb_of(mag);
                    fin_step <= 3'd5;
                end
                default: begin
                    bands[fin_idx*8 +: 8] <= e_q_comb;
                    if (fin_idx == 6'd35) begin
                        bands_valid <= 1'b1;
                        fin_busy    <= 1'b0;
                        for (gi = 0; gi < 36; gi = gi + 1) begin
                            s1[gi] <= 20'sd0;
                            s2[gi] <= 20'sd0;
                        end
                    end else begin
                        fin_idx  <= fin_idx + 1'b1;
                        f1       <= s1[fin_idx + 1'b1];
                        f2       <= s2[fin_idx + 1'b1];
                        c_fin    <= band_c(fin_idx + 1'b1);
                        fin_step <= 3'd0;
                    end
                end
                endcase
            end
        end
    end
endmodule
