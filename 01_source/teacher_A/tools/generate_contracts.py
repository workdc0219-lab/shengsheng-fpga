"""Generate local RTL contracts from authoritative JSON; --check never writes."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def outputs():
    protocol = json.loads((ROOT / 'spec/protocol_v7.json').read_text(encoding='utf-8'))
    ui = json.loads((ROOT / 'spec/ui.json').read_text(encoding='utf-8'))
    assert protocol['frame']['max_payload'] == 32
    defs = ['// GENERATED by tools/generate_contracts.py; edit spec/protocol_v7.json.']
    defs += ['localparam [7:0] V7_VERSION = 8\'d%d;' % protocol['version']]
    for name, message in protocol['messages'].items():
        assert 0 <= message['length'] <= 32
        defs += ["localparam [7:0] V7_%s = 8'd%d;" % (name, message['id']),
                 "localparam [5:0] V7_LEN_%s = 6'd%d;" % (name, message['length'])]
    defs += ['function v7_length_ok;', '    input [7:0] kind;', '    input [5:0] count;', '    begin case (kind)']
    defs += ['        V7_%s: v7_length_ok = (count == V7_LEN_%s);' % (n,n) for n in protocol['messages']]
    defs += ["        default: v7_length_ok = 1'b0;", '    endcase end', 'endfunction']
    yield 'v7_defs.vh', '\n'.join(defs) + '\n'
    defs = ['// GENERATED by tools/generate_contracts.py; edit spec/ui.json.']
    for name, color in ui['colors'].items():
        defs.append("localparam [23:0] UI_%s = 24'h%s;" % (name.upper(), color.lstrip('#')))
    for area, entries in [('CHILD',ui['child']),('TEACHER',ui['teacher'])]:
        for name, value in entries.items():
            if isinstance(value,int):
                defs.append('localparam integer UI_%s_%s = %d;' % (area,name.upper(),value))
            else:
                suffixes = ['X','Y','W','H'] if len(value)==4 else ['X','Y']
                for i, v in enumerate(value):
                    defs.append('localparam integer UI_%s_%s_%s = %d;' % (area,name.upper(),suffixes[i],v))
    yield 'ui_config.vh', '\n'.join(defs) + '\n'
    yield 'audio_config.vh', ('// Product clocks: 12.5MHz ADC / 100 cycles / 2 channels / 8 samples.\n'
          'localparam integer AUDIO_SAMPLE_RATE_NUM = 15625;\n'
          'localparam integer AUDIO_SAMPLE_RATE_DEN = 2;\n'
          'localparam integer AUDIO_PITCH_Q4_ADJ = -192;\n'
          'localparam integer AUDIO_CHILD_TMIN = 14, AUDIO_CHILD_TMAX = 104;\n'
          'localparam integer AUDIO_TEACHER_TMIN = 16, AUDIO_TEACHER_TMAX = 101;\n')

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check',action='store_true')
    args = parser.parse_args()
    pairs = []
    for name, content in outputs():
        for board in ('board_a','board_b'):
            pairs.append((ROOT/board/'src'/name, content))
    for src in sorted((ROOT/'common/rtl').glob('*.v')):
        for board in ('board_a','board_b'):
            if src.name == 'v7_link_a.v' and board != 'board_a': continue
            if src.name == 'v7_link_b.v' and board != 'board_b': continue
            pairs.append((ROOT/board/'src'/src.name,src.read_text(encoding='utf-8')))
    bad = []
    for path, content in pairs:
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                bad.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content,encoding='utf-8',newline='\n')
    if bad: raise SystemExit('CONTRACT_DRIFT: '+', '.join(bad))
    print('CONTRACT_%s files=%d' % ('CHECK_PASS' if args.check else 'GENERATED',len(pairs)))

if __name__ == '__main__': main()
